#!/bin/sh
# Installs a small loader into the SketchUp Plugins folder that loads
# Quick Views directly from this repository (development setup, macOS).
#
# Usage: tools/install_dev_loader.sh [SketchUp version, default 2027]
#        tools/install_dev_loader.sh 2026 --remove
set -e
VERSION="${1:-2027}"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
PLUGINS="$HOME/Library/Application Support/SketchUp $VERSION/SketchUp/Plugins"
TARGET="$PLUGINS/jg_quickviews_dev.rb"

if [ ! -d "$PLUGINS" ]; then
  echo "Plugins folder not found: $PLUGINS" >&2
  exit 1
fi

if [ "$2" = "--remove" ]; then
  rm -f "$TARGET"
  echo "Removed: $TARGET"
  exit 0
fi

if [ -f "$PLUGINS/jg_quickviews.rb" ]; then
  echo "Note: $PLUGINS/jg_quickviews.rb (installed release) exists. Uninstall it first," >&2
  echo "otherwise two versions are loaded." >&2
  exit 1
fi

rm -f "$PLUGINS/jviews_dev.rb" # loader of the development name "JViews"

cat > "$TARGET" <<RUBY
# Quick Views development loader (generated by tools/install_dev_loader.sh).
# Loads Quick Views from the repository; reload without restart:
#   Extensions > Quick Views > Reload   or   JG::QuickViews.reload  (Ruby console)
QUICKVIEWS_DEV_SRC = '$REPO/src'.freeze unless defined?(QUICKVIEWS_DEV_SRC)
loader = File.join(QUICKVIEWS_DEV_SRC, 'jg_quickviews.rb')
if File.exist?(loader)
  require loader
else
  warn "Quick Views dev loader: #{loader} not found"
end
RUBY
echo "Installed: $TARGET"
echo "Restart SketchUp $VERSION, then Extensions > Quick Views."
